use super::{Analysis, GeneratedRustResponse, snapshot_inputs};
use std::collections::HashMap;
use std::sync::Mutex;
use terrane_compiler::tooling::{
    Availability, DiagnosticProjection, SnapshotOptions, ToolingEngine,
};
use tower_lsp_server::ls_types::Uri;

pub(super) fn snapshot(
    uri: &Uri,
    text: &str,
    overlays: &HashMap<String, String>,
    tooling: &Mutex<ToolingEngine>,
    trusted: bool,
) -> Analysis {
    let uri_text = uri.to_string();
    let existing = tooling
        .lock()
        .expect("tooling engine lock")
        .generated_source_snapshot(&uri_text, text);
    if let Some(metadata) = existing {
        let syntax = tooling
            .lock()
            .expect("tooling engine lock")
            .syntax(&metadata.snapshot_id, &uri_text, None)
            .expect("retained generated source");
        return Analysis {
            snapshot_id: metadata.snapshot_id,
            source_texts: HashMap::from([(uri_text, text.to_owned())]),
            diagnostics: syntax.diagnostics,
        };
    }
    let (sources, manifest, testing) = snapshot_inputs(uri, text, overlays);
    let source_texts = sources
        .iter()
        .map(|source| (source.uri.clone(), source.text.clone()))
        .collect();
    let mut tooling = tooling.lock().expect("tooling engine lock");
    let metadata = match tooling.open_snapshot(
        sources,
        manifest,
        None,
        SnapshotOptions {
            semantic: true,
            allow_consumer_execution: trusted,
            testing,
            ..SnapshotOptions::default()
        },
    ) {
        Ok(metadata) => metadata,
        Err(error) => {
            return Analysis {
                snapshot_id: String::new(),
                source_texts,
                diagnostics: vec![DiagnosticProjection {
                    severity: "error".to_owned(),
                    code: "S2060".to_owned(),
                    message: format!("{}: {}", error.code, error.message),
                    span: None,
                    help: None,
                }],
            };
        }
    };
    let syntax = tooling
        .syntax(&metadata.snapshot_id, &uri_text, None)
        .expect("opened source belongs to its snapshot");
    let generated_projection = uri.to_file_path().is_some_and(|path| {
        path.ends_with(terrane_compiler::rust_interop::projection::GENERATED_PROJECTION_FILE)
    }) && text.starts_with("# Generated by Terrane. Do not edit.\n")
        && terrane_compiler::rust_interop::projection::generated_projection_units(text).is_ok();
    Analysis {
        snapshot_id: metadata.snapshot_id,
        source_texts,
        diagnostics: syntax
            .diagnostics
            .into_iter()
            .filter(|diagnostic| {
                !generated_projection
                    || !matches!(diagnostic.code.as_str(), "S0005" | "S2002" | "S2017")
            })
            .collect(),
    }
}

pub(super) fn generated_rust(
    uri: &Uri,
    text: &str,
    overlays: &HashMap<String, String>,
    tooling: &Mutex<ToolingEngine>,
    trusted: bool,
    offset: usize,
) -> Option<GeneratedRustResponse> {
    let uri_text = uri.to_string();
    let (sources, manifest, testing) = snapshot_inputs(uri, text, overlays);
    let mut tooling = tooling.lock().expect("tooling engine lock");
    let metadata = tooling
        .open_snapshot(
            sources,
            manifest,
            None,
            SnapshotOptions {
                semantic: true,
                generated: true,
                allow_consumer_execution: trusted,
                testing,
                ..SnapshotOptions::default()
            },
        )
        .ok()?;
    let response = tooling
        .locate(&metadata.snapshot_id, &uri_text, offset)
        .ok()
        .flatten()
        .map(|object| {
            let availability = if let Availability::Known(build_id) = &metadata.build_id {
                tooling
                    .generated_rust(
                        &metadata.snapshot_id,
                        &uri_text,
                        object.syntax_node_id,
                        build_id,
                    )
                    .unwrap_or(Availability::Unresolved)
            } else {
                Availability::NotYetAnalyzed
            };
            GeneratedRustResponse { availability }
        });
    let _ = tooling.close_snapshot(&metadata.snapshot_id);
    response
}
