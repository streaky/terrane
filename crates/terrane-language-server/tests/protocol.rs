use std::io::{BufRead, BufReader, Read, Write};
use std::process::{ChildStdin, ChildStdout, Command, Stdio};

use serde_json::{Value, json};

fn send(stdin: &mut ChildStdin, message: &Value) {
    let body = message.to_string();
    write!(stdin, "Content-Length: {}\r\n\r\n{body}", body.len()).unwrap();
    stdin.flush().unwrap();
}

fn receive(stdout: &mut BufReader<ChildStdout>) -> Value {
    let mut content_length = None;
    loop {
        let mut header = String::new();
        stdout.read_line(&mut header).unwrap();
        assert!(!header.is_empty(), "language server closed stdout");
        if header == "\r\n" {
            break;
        }
        if let Some(value) = header.strip_prefix("Content-Length: ") {
            content_length = Some(value.trim().parse::<usize>().unwrap());
        }
    }
    let mut body = vec![0; content_length.unwrap()];
    stdout.read_exact(&mut body).unwrap();
    serde_json::from_slice(&body).unwrap()
}

fn receive_response(stdout: &mut BufReader<ChildStdout>, id: u64) -> Value {
    loop {
        let message = receive(stdout);
        if message.get("id").and_then(Value::as_u64) == Some(id) {
            return message;
        }
    }
}

fn receive_notification(stdout: &mut BufReader<ChildStdout>, method: &str) -> Value {
    loop {
        let message = receive(stdout);
        if message.get("method").and_then(Value::as_str) == Some(method) {
            return message;
        }
    }
}

fn assert_generated_projection_edge_cases(
    stdin: &mut ChildStdin,
    stdout: &mut BufReader<ChildStdout>,
) {
    for (version, text) in [
        (
            2,
            "# Generated by Terrane. Do not edit.\n# Projection report has no admitted units.\n",
        ),
        (
            3,
            "# Generated by Terrane. Do not edit.\n# Generated source unit: /deps/witness\nnamespace deps/witness\nclass Widget\n",
        ),
    ] {
        send(
            stdin,
            &json!({
                "jsonrpc": "2.0",
                "method": "textDocument/didOpen",
                "params": {
                    "textDocument": {
                        "uri": format!("file:///tmp/generated-{version}/.trn/terrane-projection.generated.trn"),
                        "languageId": "terrane",
                        "version": version,
                        "text": text
                    }
                }
            }),
        );
        let diagnostics = receive_notification(stdout, "textDocument/publishDiagnostics");
        assert_eq!(diagnostics["params"]["version"], version);
        assert_eq!(diagnostics["params"]["diagnostics"], json!([]));
    }
    send(
        stdin,
        &json!({
            "jsonrpc": "2.0",
            "method": "textDocument/didOpen",
            "params": {
                "textDocument": {
                    "uri": "file:///tmp/authored-header.trn",
                    "languageId": "terrane",
                    "version": 4,
                    "text": "# Generated by Terrane. Do not edit.\n# Projection report has no admitted units.\n"
                }
            }
        }),
    );
    let diagnostics = receive_notification(stdout, "textDocument/publishDiagnostics");
    assert_eq!(diagnostics["params"]["version"], 4);
    assert_ne!(diagnostics["params"]["diagnostics"], json!([]));
}

#[test]
fn serves_semantic_tokens_for_an_open_document() {
    let mut child = Command::new(env!("CARGO_BIN_EXE_terrane-language-server"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    let mut stdin = child.stdin.take().unwrap();
    let mut stdout = BufReader::new(child.stdout.take().unwrap());

    send(
        &mut stdin,
        &json!({
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {"capabilities": {}}
        }),
    );
    let initialized = receive_response(&mut stdout, 1);
    assert_eq!(initialized["result"]["capabilities"]["textDocumentSync"], 1);
    assert_eq!(
        initialized["result"]["capabilities"]["semanticTokensProvider"]["full"],
        true
    );

    send(
        &mut stdin,
        &json!({"jsonrpc": "2.0", "method": "initialized", "params": {}}),
    );
    send(
        &mut stdin,
        &json!({
            "jsonrpc": "2.0",
            "method": "textDocument/didOpen",
            "params": {
                "textDocument": {
                    "uri": "file:///tmp/editor.trn",
                    "languageId": "terrane",
                    "version": 1,
                    "text": "function inline string;\n  return >hello\n\nfunction block string;\n  return >>\n    first\n    second\n"
                }
            }
        }),
    );
    let diagnostics = receive_notification(&mut stdout, "textDocument/publishDiagnostics");
    assert_eq!(diagnostics["params"]["version"], 1);
    assert_eq!(
        diagnostics["params"]["diagnostics"][0]["code"],
        json!("S2002")
    );
    send(
        &mut stdin,
        &json!({
            "jsonrpc": "2.0",
            "id": 2,
            "method": "textDocument/semanticTokens/full",
            "params": {"textDocument": {"uri": "file:///tmp/editor.trn"}}
        }),
    );
    let tokens = receive_response(&mut stdout, 2);
    let data = tokens["result"]["data"].as_array().unwrap();
    assert_eq!(data.len() % 5, 0);
    assert_eq!(tokens["result"]["resultId"], "1");
    assert_eq!(
        data.chunks(5)
            .filter(|token| token[3].as_u64() == Some(3))
            .count(),
        4
    );

    send(
        &mut stdin,
        &json!({
            "jsonrpc": "2.0",
            "method": "textDocument/didOpen",
            "params": {
                "textDocument": {
                    "uri": "file:///tmp/.trn/terrane-projection.generated.trn",
                    "languageId": "terrane",
                    "version": 1,
                    "text": "# Generated by Terrane. Do not edit.\n# Generated source unit: /deps/iced\nnamespace deps/iced\nclass Element\n# Generated source unit: /deps/iced/alignment\nnamespace deps/iced/alignment\nclass Horizontal\n"
                }
            }
        }),
    );
    let diagnostics = receive_notification(&mut stdout, "textDocument/publishDiagnostics");
    assert_eq!(diagnostics["params"]["version"], 1);
    assert_eq!(diagnostics["params"]["diagnostics"], json!([]));

    assert_generated_projection_edge_cases(&mut stdin, &mut stdout);

    send(
        &mut stdin,
        &json!({"jsonrpc": "2.0", "id": 3, "method": "shutdown", "params": null}),
    );
    let _ = receive_response(&mut stdout, 3);
    send(
        &mut stdin,
        &json!({"jsonrpc": "2.0", "method": "exit", "params": null}),
    );
    drop(stdin);
    assert!(child.wait().unwrap().success());
}

